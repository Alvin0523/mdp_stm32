static void oled_write_byte(uint8_t dat, uint8_t cmd)
{
    if (cmd)
        OLED_DC_1();
    else
        OLED_DC_0();

    for (uint8_t i = 0; i < 8; i++) {
        OLED_SCLK_0();
        if (dat & 0x80)
            OLED_SDIN_1();
        else
            OLED_SDIN_0();
        OLED_SCLK_1();
        dat <<= 1;
    }
}

static void oled_set_pos(uint8_t x, uint8_t y)
{
    oled_write_byte(0xb0 + y, 0);
    oled_write_byte(((x & 0xf0) >> 4) | 0x10, 0);
    oled_write_byte((x & 0x0f), 0);
}

void oled_clear(void)
{
    for (uint8_t i = 0; i < 8; i++) {
        oled_set_pos(0, i);
        for (uint8_t n = 0; n < 128; n++) {
            oled_write_byte(0x00, 1);
        }
    }
}

void oled_init(void)
{
    __HAL_RCC_GPIOD_CLK_ENABLE();

    GPIO_InitTypeDef GPIO_InitStruct = {0};
    GPIO_InitStruct.Pin = GPIO_PIN_11 | GPIO_PIN_12 | GPIO_PIN_13 | GPIO_PIN_14;
    GPIO_InitStruct.Mode = GPIO_MODE_OUTPUT_PP;
    GPIO_InitStruct.Pull = GPIO_NOPULL;
    GPIO_InitStruct.Speed = GPIO_SPEED_FREQ_HIGH;
    HAL_GPIO_Init(GPIOD, &GPIO_InitStruct);

    OLED_RST_0();
    HAL_Delay(50);
    OLED_RST_1();

    oled_write_byte(0xAE, 0); /* Display OFF */
    oled_write_byte(0x00, 0); /* Set Low Column Address */
    oled_write_byte(0x10, 0); /* Set High Column Address */
    oled_write_byte(0x40, 0); /* Set Start Line Address */
    oled_write_byte(0x81, 0); /* Set Contrast Control */
    oled_write_byte(0xCF, 0);
    oled_write_byte(0xA1, 0); /* Set Segment Re-map */
    oled_write_byte(0xC8, 0); /* Set COM Output Scan Direction */
    oled_write_byte(0xA6, 0); /* Set Normal Display */
    oled_write_byte(0xA8, 0); /* Set Multiplex Ratio */
    oled_write_byte(0x3F, 0);
    oled_write_byte(0xD3, 0); /* Set Display Offset */
    oled_write_byte(0x00, 0);
    oled_write_byte(0xD5, 0); /* Set Display Clock Divide Ratio */
    oled_write_byte(0x80, 0);
    oled_write_byte(0xD9, 0); /* Set Pre-charge Period */
    oled_write_byte(0xF1, 0);
    oled_write_byte(0xDA, 0); /* Set COM Pins Hardware Configuration */
    oled_write_byte(0x12, 0);
    oled_write_byte(0xDB, 0); /* Set VCOMH Deselect Level */
    oled_write_byte(0x40, 0);
    oled_write_byte(0x8D, 0); /* Set Charge Pump Enable */
    oled_write_byte(0x14, 0);
    oled_write_byte(0xAF, 0); /* Display ON */

    oled_clear();
}

/**
 * @brief Render 8x16 string with explicit x_offset
 */
void oled_show_string_8x16_offset(uint8_t row, uint8_t x_offset, const char *str)
{
    uint8_t x = x_offset;
    uint8_t y = row * 2; /* 8x16 font consumes 2 pages */

    uint8_t count = 0;
    while (*str && count < 16) {
        uint8_t c = *str - ' ';
        if (c > 94) c = 0;

        oled_set_pos(x, y);
        for (uint8_t i = 0; i < 8; i++) {
            oled_write_byte(g_asc2_1608[c][i], 1);
        }

        oled_set_pos(x, y + 1);
        for (uint8_t i = 0; i < 8; i++) {
            oled_write_byte(g_asc2_1608[c][i + 8], 1);
        }

        x += 8;
        str++;
        count++;
    }
}

void oled_render_page1(float battery_v, uint8_t estop_state, float left_speed, float right_speed, float steer_deg, float yaw_deg)
{
    char buf[16];

    /* Fixed field width (%4.1f) so "9.9" and "10.0" render as the same
     * total character count - oled_show_string_8x16_offset() only
     * overwrites glyph cells for the new string's own length, so a shorter
     * string here would leave a stray glyph from the previous longer one
     * (this is what caused "9.9VV" - the trailing V from "10.0V" never got
     * erased when the value dropped to one digit).
     *
     * Was "SYS:OK ..." before - that label was hardcoded, never actually
     * reflecting any real check (would still say "OK" even if the IMU
     * failed to init). Just labels the number now instead of pretending
     * to be a status check it isn't. */
    snprintf(buf, sizeof(buf), "BATT: %4.1fV", battery_v);
    oled_show_string_8x16_offset(0, 12, buf);

    /* Same fixed-width reasoning: "ENGAGED" (7 chars) and "READY" both need
     * to render at 7 characters, or the shorter one leaves a stray glyph
     * behind (this caused a leftover "D" from "ENGAGED" persisting after
     * switching to "READY"). */
    snprintf(buf, sizeof(buf), "ESTOP: %-7s", estop_state ? "ENGAGED" : "READY");
    oled_show_string_8x16_offset(1, 12, buf);

    /* Display is 128px wide, this row starts at x=12, so there's only
     * 116px = 14.5 chars of room - oled_set_pos()/oled_write_byte() never
     * bounds-check x, so writing past column 127 wraps onto the next
     * page instead of erroring. "%.2f" with no width was unbounded and
     * already overflowed by 12px even at everyday values (e.g.
     * "L:12.34  R:12.34" = 16 chars = 128px, right at the edge with zero
     * margin) - %4.1f fixes both the width AND drops to a fixed field so
     * it can't grow past this budget. */
    snprintf(buf, sizeof(buf), "L:%4.1f R:%4.1f", (double)left_speed, (double)right_speed);
    oled_show_string_8x16_offset(2, 12, buf);

    /* Y = yaw, degrees - this board's own raw gyro-integrated estimate
     * (imu.c), not the Pi-side EKF's fused /odometry/filtered heading.
     * Same overflow fix as above - steer realistically stays within
     * width 3 (+/-35 max), yaw needs width 4 to safely hold 3-digit
     * swings (+180 etc) without exceeding its field. */
    snprintf(buf, sizeof(buf), "STR:%+3.0f Y:%+4.0f", (double)steer_deg, (double)yaw_deg);
    oled_show_string_8x16_offset(3, 12, buf);
}

void oled_render_page2(float us_cm, float ir_cm, int32_t enc_left, int32_t enc_right)
{
    char buf[16];
    char numbuf[8];

    oled_show_string_8x16_offset(0, 12, "==SENSORS====");

    /* Same fixed-width fix as page 1's battery/ESTOP lines: format the
     * number into a constant-width field first (5 chars either way) so
     * "--" doesn't leave stray glyphs behind from a previous longer
     * reading. */
    if (us_cm >= 0.0f) {
        snprintf(numbuf, sizeof(numbuf), "%5.1f", (double)us_cm);
    } else {
        snprintf(numbuf, sizeof(numbuf), "  -- ");
    }
    snprintf(buf, sizeof(buf), "Ultra:%scm", numbuf);
    oled_show_string_8x16_offset(1, 12, buf);

    /* Only one physical IR sensor is wired (ir_sensor.c), despite
     * docs/hardware.md listing two - shown once, in cm only, rather than
     * the raw ADC count and volts it used to also print alongside it. */
    snprintf(buf, sizeof(buf), "IR:   %5.1fcm", (double)ir_cm);
    oled_show_string_8x16_offset(2, 12, buf);

    /* Encoder counts merged in here (was a separate page) - uptime dropped,
     * it wasn't something anyone was actually checking on this screen.
     * "ENC left:right" rather than page 1's "L:.. R:.." style on purpose -
     * page 1's L/R is wheel SPEED (ticks/sec), this is cumulative tick
     * COUNT, a different quantity entirely; matching labels across both
     * would make them look like the same thing at a glance.
     * Width 5 kept (not 4) since encoder counts can run into 5 digits
     * over a session, unlike the small values on page 1 - the "R: 0"
     * overflow was from the old label/spacing overhead, not the value
     * itself, so tightening ENC's own label recovers that margin instead
     * of shrinking the numbers' actual range. */
    snprintf(buf, sizeof(buf), "ENC%5ld:%5ld", (long)enc_left, (long)enc_right);
    oled_show_string_8x16_offset(3, 12, buf);
}

void oled_next_page(void)
{
    g_oled_page = (g_oled_page + 1) % 2; /* Loop through 2 pages */
    oled_clear();
}
